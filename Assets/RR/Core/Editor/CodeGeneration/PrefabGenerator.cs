using System;
using System.Collections.Generic;
using System.IO;
using RR.Core.DebugSystem;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace RR.Core.Editor.CodeGeneration
{
    #if UNITY_EDITOR
    public static class PrefabGenerator
    {
        public const string DefaultFolderLocation = "Assets/AutoGenerated/Prefabs";
        public const string PrefabExtension = ".prefab";

        public static void GenerateFromTemplate(string name, string templatePath, string saveFolderPath = DefaultFolderLocation)
        {
            if (!File.Exists(templatePath))
                throw new NullReferenceException($"There is no file at path: {templatePath}");
            
            var obj = PrefabUtility.LoadPrefabContents(templatePath);
            
            SavePrefab(name, obj, saveFolderPath);
            
            PrefabUtility.UnloadPrefabContents(obj);
        }        
        
        public static void Generate(string name, IEnumerable<Type> components, string saveFolderPath = DefaultFolderLocation)
        {
            var obj = new GameObject(name);
            
            foreach (var compType in components)
                obj.AddComponent(compType);

            SavePrefab(name, obj, saveFolderPath);
            
            Object.DestroyImmediate(obj);
        }

        public static GameObject SavePrefab(string fileName, GameObject obj, string folderPath, bool connect = false)
        {
            if (!Directory.Exists(folderPath))
                Directory.CreateDirectory(folderPath);
            
            string path = Path.Combine(folderPath, $"{fileName}{PrefabExtension}");

            if (File.Exists(path))
            { 
                RRLogger.Error($"Prefab at path: [{path}] is already exists!");
                return null;
            }

            RRLogger.Log($"Generated prefab: {fileName} at path: {folderPath}");
            
            return connect ? 
                PrefabUtility.SaveAsPrefabAssetAndConnect(obj, path, InteractionMode.AutomatedAction) : 
                PrefabUtility.SaveAsPrefabAsset(obj, path);
        }
    }
    #endif
}